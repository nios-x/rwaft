/** Writes the design schema, tokens, kit, layout and router. Returns the files written. */
export async function writeFoundation(projectDir: string, plan: AppPlan): Promise<string[]> {
	const files: Record<string, string> = {
		"src/design.ts": designModule(plan),
		"src/index.css": indexCss(plan),
		"src/App.tsx": appModule(plan),
		"src/components/Layout.tsx": plan.layout === "bare" ? BARE_LAYOUT : SITE_LAYOUT,
		"index.html": indexHtml(plan),
		"public/favicon.svg": favicon(plan),
		...KIT,
	}
	for (const [file, content] of Object.entries(files)) {
		const target = path.join(projectDir, file)
		await fs.mkdir(path.dirname(target), { recursive: true })
		await fs.writeFile(target, content, "utf-8")
	}
	return Object.keys(files)
}
