/**
 * Step 2 of generation: the foundation, written by code instead of the model.
 *
 * From the plan's design schema this writes everything the pages share:
 * src/design.ts (the schema itself, which the site reads), the Tailwind tokens
 * in src/index.css, a small component kit themed by those tokens, the layout
 * and the router. None of it costs a model call, all of it is known to
 * compile, and because every page is written against the same files, pages
 * generated in parallel still look like one product.
 *
 * Lovable, Dyad and llama-coder all do a version of this: the model composes
 * from components that already exist instead of reinventing a button per page.
 */

const RADIUS: Record<Radius, string> = { none: "0px", sm: "0.375rem", md: "0.625rem", lg: "0.875rem", xl: "1.25rem" }

const SERIF = new Set(["Playfair Display", "Fraunces", "DM Serif Display", "Instrument Serif", "Cormorant Garamond", "Lora", "Libre Baskerville", "Merriweather"])
const MONO = new Set(["Space Mono", "JetBrains Mono", "Press Start 2P"])

const fontStack = (family: string) =>
	`"${family}", ${SERIF.has(family) ? "ui-serif, Georgia, serif" : MONO.has(family) ? "ui-monospace, monospace" : "ui-sans-serif, system-ui, sans-serif"}`

const fontImport = (families: string[]) => {
	const query = [...new Set(families)]
		.map((family) => `family=${family.replace(/ /g, "+")}:wght@${FONTS[family] ?? "400;700"}`)
		.join("&")
	return `https://fonts.googleapis.com/css2?${query}&display=swap`
}

/** camelCase palette role → Tailwind token name, e.g. cardForeground → card-foreground. */
const tokenName = (role: string) => role.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`)

function indexCss(plan: AppPlan): string {
	const { palette, fonts, radius, mode } = plan.design
	const colors = (Object.keys(palette) as Array<keyof Palette>)
		.map((role) => `\t--color-${tokenName(role)}: ${palette[role]};`)
		.join("\n")

	return `/* Design tokens from src/design.ts, generated by rwaft. Use the utilities they
   create (bg-primary, text-muted-foreground, font-heading, rounded-ui) instead
   of raw colours, so every page stays on one palette. */
@import url("${fontImport([fonts.heading, fonts.body])}");
@import "tailwindcss";

@theme {
${colors}
	--font-heading: ${fontStack(fonts.heading)};
	--font-body: ${fontStack(fonts.body)};
	--radius-ui: ${RADIUS[radius]};
}

@layer base {
	:root {
		color-scheme: ${mode};
	}
	body {
		background-color: var(--color-background);
		color: var(--color-foreground);
		font-family: var(--font-body);
		-webkit-font-smoothing: antialiased;
	}
	h1, h2, h3, h4, h5, h6 {
		font-family: var(--font-heading);
		text-wrap: balance;
	}
	::selection {
		background: color-mix(in srgb, var(--color-primary) 28%, transparent);
	}
	:focus-visible {
		outline: 2px solid var(--color-ring);
		outline-offset: 2px;
	}
	/* In-page links land below the sticky header, not under it. */
	[id] {
		scroll-margin-top: 5rem;
	}
	/* No double-tap zoom delay on taps. */
	a, button, [role="button"], input, label, select, textarea {
		touch-action: manipulation;
	}
}

@media (prefers-reduced-motion: reduce) {
	*, *::before, *::after {
		animation-duration: 0.01ms !important;
		animation-iteration-count: 1 !important;
		transition-duration: 0.01ms !important;
		scroll-behavior: auto !important;
	}
}
`
}

function designModule(plan: AppPlan): string {
	const schema = {
		name: plan.name,
		tagline: plan.tagline,
		kind: plan.kind,
		layout: plan.layout,
		pages: plan.pages.map((page) => ({ name: page.name, path: page.path })),
		design: plan.design,
		// Set to true by lib/photos.ts when the site uses Pexels photos; the
		// layout then shows the credit Pexels asks for.
		photoCredit: false,
	}
	return `/**
 * The design schema for this site, written by rwaft from the build plan.
 * Its colours and fonts are also Tailwind tokens in src/index.css: style with
 * those utilities (bg-primary, text-muted-foreground, font-heading) rather than
 * reading the raw values here.
 */
export const site = ${JSON.stringify(schema, null, "\t")} as const
`
}

